const { withAppBuildGradle } = require("expo/config-plugins");

const SPLIT_BLOCK_START = "// @generated by with-android-abi-splits";
const ANDROID_BLOCK = "android {";
const ABI_SPLIT_BLOCK = `
    ${SPLIT_BLOCK_START}
    splits {
        abi {
            reset()
            enable true
            universalApk false
            include "armeabi-v7a", "arm64-v8a", "x86", "x86_64"
        }
    }
`;

function addAndroidAbiSplits(contents) {
  if (contents.includes(SPLIT_BLOCK_START)) return contents;

  const androidBlockCount = contents.split(ANDROID_BLOCK).length - 1;
  if (androidBlockCount !== 1) {
    throw new Error(
      `Expected one Android Gradle block, found ${androidBlockCount}`,
    );
  }

  return contents.replace(ANDROID_BLOCK, `${ANDROID_BLOCK}${ABI_SPLIT_BLOCK}`);
}

const withAndroidAbiSplits = (config) =>
  withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") {
      throw new Error("Android ABI split configuration requires Groovy Gradle");
    }

    gradleConfig.modResults.contents = addAndroidAbiSplits(
      gradleConfig.modResults.contents,
    );
    return gradleConfig;
  });

module.exports = withAndroidAbiSplits;
module.exports.addAndroidAbiSplits = addAndroidAbiSplits;
